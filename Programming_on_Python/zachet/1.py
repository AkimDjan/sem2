import numpy as np

a = [
    'x2+y2+z2-m=0',
    'x2+y2+z2+m=0',
    'x2+y2+z2=0',
    'x2+y2-z2-m=0',
    'x2+y2-z2+m=0',
    'x2+y2-z2=0',

    'x2+y2-z=0',
    'x2-y2-z=0',
    'x2+y2-m=0',
    'x2+y2+m=0',
    'x2+y2=0',
    'x2-y2-m=0',
    'x2-y2=0',

    'x2-m=0',
    'x2+m=0',
    'x2=0',
    'x2+y+m=0'
]

b = [
    'эллипсоид',
    'мнимый эллипсоид',
    'точка',
    'однополостный гиперболоид',
    'двуполостный гиперболоид',
    'конус',

    'эллиптический параболоид',
    'гиперболический параболоид',
    'эллиптический цилиндр',
    'мнимый эллиптический цилиндр',
    'прямая/пара мнимых пересекающихся плоскостей',
    'гиперболический цилиндр',
    'пара пересекающихся плоскостей',

    'пара параллельных плоскостей',
    'пара мнимых параллельных плоскостей',
    'пара совпавших плоскостей',
    'параболический цилиндр',
]

print("Выбери правильный номер названия поверхности:")
for i, j in enumerate(b):
    print(f"{i}: {j}")

ind = np.random.permutation(len(a))

score = 0

for idx in ind:
    print(f"\nУравнение: {a[idx]}")
    answer = input("Ваш ответ (номер): ")

    # Проверка ввода
    if not answer.isdigit():
        print("Введите число.")
        continue

    if int(answer) == idx:
        print("✅ Правильно!")
        score += 1
    else:
        print(f"❌ Неправильно. Правильный ответ: {b[idx]} (№{idx})")

print(f"\nИтог: {score} из {len(a)} правильных.")